
// Alphabetical sorting in array
let fruits = ["Pineapple","","Banana","Kiwi","Mango"];
console.log(fruits);
fruits.sort();
console.log("After sorting")
console.log(fruits); // [ '', 'Banana', 'Kiwi', 'Mango', 'Pineapple' ] 
// blank/empty is put first and then alphabetical order

let newFruits=["Mango","Apple","Argon","Manjal"];
